package entidades;

/**
 *
 * @author Mario Valdez
 */
public class Actividades {
    private String id;
    private String actividad;

    public Actividades() {
    }

    public Actividades(String id, String actividad) {
        this.id = id;
        this.actividad = actividad;
    }

    public String getId() {
        return id;
    }

    public void setId(String id) {
        this.id = id;
    }

    public String getActividad() {
        return actividad;
    }

    public void setActividad(String actividad) {
        this.actividad = actividad;
    }
    
    
}
